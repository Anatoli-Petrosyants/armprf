#!/usr/bin/env node
/**
 * Regenerates src/content/config/images.md from the image paths the site
 * actually references, so the manifest can never drift from the code.
 *
 *   npm run images
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(process.cwd());
const CONTENT = join(ROOT, 'src/content');
const ASSETS = join(ROOT, 'src/assets/img');

const SPECS = [
  { match: /^\/img\/brand\/hero\//, ratio: '16:9', min: '2560×1440', note: 'Text-safe area on the left third.' },
  { match: /^\/img\/brand\/portraits\//, ratio: '1:1', min: '1000×1000', note: 'Head and shoulders, eyes on the upper third.' },
  { match: /^\/img\/about\//, ratio: '1:1', min: '1100×1100', note: 'About page pair, shown side by side.' },
  { match: /^\/img\/brand\/og\//, ratio: '1.91:1', min: '1200×630', note: 'Social sharing fallback.' },
  { match: /^\/img\/brand\/logo\//, ratio: '1:1', min: 'SVG', note: 'Light and dark variants, transparent background.' },
  { match: /^\/img\/brand\/sponsors\//, ratio: '12:5', min: 'SVG or 480×200', note: 'Monochrome, uses currentColor when SVG.' },
  { match: /^\/img\/posts\//, ratio: '16:9', min: '1920×1080', note: 'Blog cover.' },
  { match: /^\/img\/events\//, ratio: '16:9', min: '1920×1080', note: 'Event cover; also cropped to 3:4 in list view.' },
  { match: /^\/img\/challenges\//, ratio: '16:9', min: '1920×1080', note: 'Challenge hero; shown at 21:9 with an overlay.' },
  { match: /.*/, ratio: '3:2', min: '1600×1067', note: 'Gallery photo.' },
];

const specFor = (path) => SPECS.find((s) => s.match.test(path));

function walk(dir, fn) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, fn);
    else fn(full);
  }
}

const refs = new Map();
walk(CONTENT, (file) => {
  if (!/\.(json|md)$/.test(file)) return;
  const text = readFileSync(file, 'utf-8');
  for (const m of text.matchAll(/\/img\/[A-Za-z0-9._\/-]+\.(?:jpg|jpeg|png|svg|webp)/g)) {
    const rel = file.replace(`${ROOT}/`, '');
    if (!refs.has(m[0])) refs.set(m[0], new Set());
    refs.get(m[0]).add(rel);
  }
});

[
  '/img/brand/logo/armprf-logo-dark.svg',
  '/img/brand/logo/armprf-logo-themed.svg',
  '/img/brand/logo/armprf-wordmark-themed.svg',
].forEach((p) => {
  if (!refs.has(p)) refs.set(p, new Set(['src/components (referenced directly)']));
});

const paths = [...refs.keys()].sort();
const groups = new Map();
for (const path of paths) {
  const folder = path.slice(0, path.lastIndexOf('/'));
  if (!groups.has(folder)) groups.set(folder, []);
  groups.get(folder).push(path);
}

const present = (path) => existsSync(join(ASSETS, path.replace('/img/', '')));

// Folders already holding real artwork rather than generated stand-ins.
const REAL = ['/img/brand/logo/', '/img/brand/hero/', '/img/about/'];

const lines = [
  '# Photo manifest',
  '',
  '_Generated by `npm run images`. Do not edit by hand; edit the content files it reads._',
  '',
  'Every image the site expects, with the folder it belongs in, the aspect ratio it is',
  'cropped to, and the minimum resolution worth uploading. Drop a real file at the given',
  'path and it replaces the placeholder automatically, because the build never overwrites a file',
  'that already exists.',
  '',
  '## How paths work',
  '',
  '- A content file writes `"/img/match/targets/photo.jpg"`.',
  '- The build looks for `src/assets/img/match/targets/photo.jpg`.',
  '- Astro then generates AVIF, WebP and JPEG variants at the sizes each layout needs.',
  '- Keep your originals somewhere else. Do not commit anything larger than about 3 MB.',
  '',
  '## Naming convention',
  '',
  '```',
  'YYYY-MM-DD_tag_short-description_01.jpg',
  '2026-05-17_match-stage-firing_gyumri-round2_03.jpg',
  '```',
  '',
  'Landscape 3:2 or 16:9 for galleries and heroes, 1:1 for portraits. JPEG quality 90,',
  'longest edge at least 2000 px.',
  '',
  `## Slots (${paths.length} total)`,
  '',
  'Status `placeholder` means a generated stand-in is in place and the real photo is still missing.',
  '',
];

for (const [folder, items] of [...groups.entries()].sort()) {
  const spec = specFor(`${folder}/x.jpg`);
  lines.push(`### \`${folder}/\``, '');
  lines.push(`Aspect **${spec.ratio}** · minimum **${spec.min}** · ${spec.note}`, '');
  lines.push('| File | Status | Referenced by |', '| --- | --- | --- |');
  for (const path of items) {
    const file = path.slice(folder.length + 1);
    const real = REAL.some((prefix) => path.startsWith(prefix));
    const status = !present(path) ? 'missing' : real ? '**real**' : 'placeholder';
    const used = [...refs.get(path)].map((r) => `\`${r.split('/').pop()}\``).join(', ');
    lines.push(`| \`${file}\` | ${status} | ${used} |`);
  }
  lines.push('');
}

// The shooting plan is documented here rather than derived, so it survives even
// when no content file currently points at a given folder.
const PLAN = [
  ['Competition', 'match/', [
    ['stage-firing', 'Shooter behind the rifle on a stage, bipod or tripod, spotter beside'],
    ['prone-positional', 'Prone, barricade, tank trap, roof-top prop'],
    ['timers-and-scoring', 'RO with a timer, score card close-up'],
    ['targets', 'Steel at distance, KYL rack, impact splash'],
    ['podium', 'Top three with awards, and the whole field'],
    ['gear-line', 'Rifles racked at the line, bipods, chrono session'],
  ]],
  ['Rimfire / .22LR', 'rimfire/', [
    ['matches', 'Rimfire match at short distances'],
    ['kids-and-newcomers', 'First shots under a coach'],
    ['small-targets', 'Mini steel at 100 m and under'],
  ]],
  ['Long range', 'longrange/', [
    ['1000m-plus', 'Shooter, spotting scope, wind flags'],
    ['wind-reading', 'Kestrel, flags, mirage'],
    ['dope-and-ballistics', 'Data book, ballistic app, turret close-up'],
  ]],
  ['Training', 'training/', [
    ['zeroing', '100 m groups on paper'],
    ['dry-fire-and-positions', 'Positional work without ammunition'],
    ['coaching', 'Instructor correcting a position'],
    ['safety-briefing', 'Everyone in eyes and ears, muzzle discipline'],
    ['reloading-bench', 'Press, brass, powder, seating dies'],
  ]],
  ['Hunting / ethical shooting', 'hunting/', [
    ['field-positions', 'Improvised rests, packs, terrain'],
    ['500yd-challenge', 'Runs from the Ethical Hunter Challenge'],
    ['landscape', 'Armenian terrain, giving a sense of distance'],
  ]],
  ['Range & construction', 'range/', [
    ['construction-progress', 'Dated: earthworks, berms, firing line, target frames'],
    ['facilities', 'Benches, signage, shade, parking'],
    ['before-after', 'Pairs, shot from the same spot'],
  ]],
  ['Community', 'community/', [
    ['birthday-and-celebrations', 'Federation celebrations'],
    ['group-photos', 'Members and team photos'],
    ['barbecue-and-camp', 'Overnight matches, camp life'],
    ['kids-and-families', 'Family days at the range'],
    ['international-guests', 'Visiting shooters and coaches'],
  ]],
];

lines.push(
  '## What to shoot',
  '',
  'The folders below are the agreed taxonomy. A folder only appears in the table above',
  'once a content file points at a photo inside it. Shoot for all of them anyway, and the',
  'names will line up when you publish.',
  '',
);
for (const [group, prefix, tags] of PLAN) {
  lines.push(`**${group}** (\`/img/${prefix}\`)`, '');
  for (const [tag, note] of tags) {
    lines.push(`- \`${prefix}${tag}/\`: ${note}`);
  }
  lines.push('');
}
lines.push(
  '**Brand assets** (`/img/brand/`)',
  '',
  '- `brand/logo/`: the federation wordmark, light and dark, plus the themable copy',
  '- `brand/hero/`: 3–5 landscape frames, min 2560×1440, text-safe area on the left',
  '- `brand/portraits/`: one square headshot per athlete, min 1000×1000',
  '- `about/`: the two square frames shown on the About page',
  '',
);

lines.push(
  '## Video',
  '',
  'Videos are never uploaded to the repository. Set `videoUrl` on a post or a challenge.',
  'The player is a click-to-load facade, so nothing is requested from YouTube until a',
  'visitor asks for it.',
  '',
);

writeFileSync(join(CONTENT, 'config/images.md'), lines.join('\n'));
console.log(`images.md written — ${paths.length} slots across ${groups.size} folders`);
